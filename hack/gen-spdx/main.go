// gen-spdx writes the table of SPDX licence identifiers DL3054 accepts, from
// the licenses.json of a release of the SPDX License List.
package main

import (
	"encoding/json"
	"errors"
	"fmt"
	"go/format"
	"os"
	"slices"
	"strings"
)

// ErrGeneration is the base error of a failed generation.
var ErrGeneration = errors.New("spdx table generation error")

// output is the file written, in the directory the generator runs in.
const output = "spdx.go"

// list is what the generator reads of licenses.json.
type list struct {
	Version  string    `json:"licenseListVersion"`
	Licenses []license `json:"licenses"`
}

type license struct {
	ID         string `json:"licenseId"`
	Deprecated bool   `json:"isDeprecatedLicenseId"`
}

func main() {
	if len(os.Args) != 2 {
		_, _ = fmt.Fprintf(os.Stderr, "Usage: %s <licenses.json>\n", os.Args[0])

		os.Exit(1)
	}

	if err := generate(os.Args[1]); err != nil {
		_, _ = fmt.Fprintln(os.Stderr, err)

		os.Exit(1)
	}
}

func generate(path string) error {
	// #nosec G304 G703 -- the licenses.json of the pinned list, named by the caller
	data, err := os.ReadFile(path)
	if err != nil {
		return fmt.Errorf("%w: %w", ErrGeneration, err)
	}

	source, count, err := render(data)
	if err != nil {
		return err
	}

	file, err := os.Create(output)
	if err != nil {
		return fmt.Errorf("%w: %w", ErrGeneration, err)
	}

	defer func() {
		_ = file.Close()
	}()

	if _, err := file.Write(source); err != nil {
		return fmt.Errorf("%w: %w", ErrGeneration, err)
	}

	fmt.Printf("Generated %s (%d identifiers)\n", output, count)

	return nil
}

// render is the Go source of the table for a licenses.json, and how many
// identifiers it holds: every identifier of the list that is not deprecated,
// in order.
func render(data []byte) ([]byte, int, error) {
	var spdx list

	if err := json.Unmarshal(data, &spdx); err != nil {
		return nil, 0, fmt.Errorf("%w: %w", ErrGeneration, err)
	}

	var ids []string

	for _, entry := range spdx.Licenses {
		if !entry.Deprecated && entry.ID != "" {
			ids = append(ids, entry.ID)
		}
	}

	if spdx.Version == "" || len(ids) == 0 {
		return nil, 0, fmt.Errorf("%w: no version or no identifier in the list", ErrGeneration)
	}

	slices.Sort(ids)

	var out strings.Builder

	fmt.Fprintf(&out, `// Code generated by go generate; DO NOT EDIT.
// This file is auto-generated from the SPDX License List %[1]s.

package rules

// spdxLicenses is every licence identifier of the SPDX License List %[1]s
// that is not deprecated there.
//
//nolint:gochecknoglobals // a constant table
var spdxLicenses = map[string]struct{}{
`, spdx.Version)

	for _, id := range ids {
		fmt.Fprintf(&out, "\t%q: {},\n", id)
	}

	out.WriteString("}\n")

	source, err := format.Source([]byte(out.String()))
	if err != nil {
		return nil, 0, fmt.Errorf("%w: %w", ErrGeneration, err)
	}

	return source, len(ids), nil
}
